counters = {"listing": 0, "table": 0, "figure": 0}


def add(xml):
    body.insert(len(body) - 1, parse_xml(xml))


def runs(text, size=None, base_size=None):
    """Текст с `инлайн-кодом` -> набор w:r. Код набирается Courier New."""
    out = []
    for i, part in enumerate(re.split(r"`", text)):
        if not part:
            continue
        code = i % 2 == 1
        sz = size if code else base_size
        rpr = (COURIER if code else "") + '<w:color w:val="000000"/>' + (f'<w:sz w:val="{sz}"/>' if sz else "")
        out.append(f'<w:r><w:rPr>{rpr}</w:rPr><w:t xml:space="preserve">{escape(part)}</w:t></w:r>')
    return "".join(out)


def heading(text):
    add(f'<w:p {W}><w:pPr><w:pStyle w:val="1"/><w:pageBreakBefore/>'
        '<w:keepNext/><w:ind w:firstLine="0"/><w:jc w:val="center"/></w:pPr>'
        f'{runs(text)}</w:p>')
    toc_entries.append((text, 1))


def subheading(text):
    pagebreak = '<w:pageBreakBefore/>' if text in ['А.2 Команды воспроизведения', 'А.3 Репозиторий исходного кода'] else ''
    add(f'<w:p {W}><w:pPr><w:pStyle w:val="21"/>{pagebreak}<w:keepNext/></w:pPr>'
        f'{runs(text)}</w:p>')
    toc_entries.append((text, 2))


def para(text):
    add(f'<w:p {W}><w:pPr/>{runs(text, size=26)}</w:p>')


def caption(kind, title):
    counters[kind] += 1
    word = {"listing": "Листинг", "table": "Таблица"}[kind]
    add(f'<w:p {W}><w:pPr><w:keepNext/><w:ind w:firstLine="0"/><w:jc w:val="left"/></w:pPr>'
        f'{runs(f"{word} {counters[kind]} – {title}")}</w:p>')
    return counters[kind]


def spacer():
    add(f'<w:p {W}><w:pPr><w:spacing w:line="240" w:lineRule="auto"/></w:pPr></w:p>')


def listing(title, code):
    caption("listing", title)
    lines = "".join(
        f'<w:p><w:pPr><w:spacing w:line="240" w:lineRule="auto"/><w:ind w:firstLine="0"/><w:jc w:val="left"/></w:pPr>'
        f'<w:r><w:rPr>{COURIER}<w:color w:val="000000"/><w:sz w:val="18"/></w:rPr>'
        f'<w:t xml:space="preserve">{escape(line)}</w:t></w:r></w:p>'
        for line in code.rstrip("\n").split("\n"))
    add(f'<w:tbl {W}><w:tblPr><w:tblStyle w:val="aff0"/><w:tblW w:w="0" w:type="auto"/><w:jc w:val="center"/>'
        f'<w:tblLayout w:type="fixed"/><w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" w:firstColumn="1" '
        f'w:lastColumn="0" w:noHBand="0" w:noVBand="1"/></w:tblPr><w:tblGrid><w:gridCol w:w="9354"/></w:tblGrid>'
        f'<w:tr><w:trPr><w:cantSplit/><w:jc w:val="center"/></w:trPr><w:tc><w:tcPr><w:tcW w:w="9354" w:type="dxa"/></w:tcPr>'
        f'{lines}</w:tc></w:tr></w:tbl>')
    spacer()


def table(title, header, rows, widths):
    caption("table", title)

    def cell(text, w, head=False, first=False):
        jc = "center" if head else "left"
        if head:
            content = f'<w:r><w:rPr><w:b/><w:color w:val="000000"/><w:sz w:val="24"/></w:rPr><w:t>{escape(text)}</w:t></w:r>'
        else:
            content = runs(text, size=22, base_size=24)
        return (f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/></w:tcPr><w:p><w:pPr><w:spacing w:line="240" '
                f'w:lineRule="auto"/><w:ind w:firstLine="0"/><w:jc w:val="{jc}"/></w:pPr>{content}</w:p></w:tc>')

    def row(cells, head=False):
        return ('<w:tr><w:trPr><w:cantSplit/><w:jc w:val="center"/>' + ('<w:tblHeader/>' if head else '') +
                '</w:trPr>' + "".join(cell(c, w, head) for c, w in zip(cells, widths)) + '</w:tr>')

    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    add(f'<w:tbl {W}><w:tblPr><w:tblStyle w:val="aff0"/><w:tblW w:w="0" w:type="auto"/><w:jc w:val="center"/>'
        f'<w:tblLayout w:type="fixed"/><w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" w:firstColumn="1" '
        f'w:lastColumn="0" w:noHBand="0" w:noVBand="1"/></w:tblPr><w:tblGrid>{grid}</w:tblGrid>'
        + row(header, True) + "".join(row(r) for r in rows) + '</w:tbl>')
    spacer()


def figure(title, width=16, filename=None):
    counters["figure"] += 1
    n = counters["figure"]
    shot = SHOTS / (filename or f"{n:02d}.png")
    if not shot.exists():
        raise FileNotFoundError(shot)
    add(f'<w:p {W}><w:pPr><w:keepNext/><w:spacing w:before="120" w:line="240" w:lineRule="auto"/>'
        '<w:ind w:firstLine="0"/><w:jc w:val="center"/></w:pPr></w:p>')
    p = docx.text.paragraph.Paragraph(body[len(body) - 2], doc._body)
    p.add_run().add_picture(str(shot), width=Cm(width))
    add(f'<w:p {W}><w:pPr><w:spacing w:after="120"/><w:ind w:firstLine="0"/><w:jc w:val="center"/></w:pPr>'
        f'{runs(f"Рисунок {n} – {title}")}</w:p>')
    return n


def extract(path, start):
    """Фрагмент исходника: от строки, начинающейся с start, до закрывающей скобки того же отступа."""
    lines = (ROOT / path).read_text(encoding="utf-8").split("\n")
    i = next(k for k, l in enumerate(lines) if l.strip().startswith(start))
    indent = len(lines[i]) - len(lines[i].lstrip())
    j = next(k for k in range(i + 1, len(lines)) if lines[k] == " " * indent + "}")
    return "\n".join(l[indent:] for l in lines[i:j + 1])


